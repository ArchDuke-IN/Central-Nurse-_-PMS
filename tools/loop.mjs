/**
 * PMS build loop.
 *
 *   node tools/loop.mjs            assemble, verify, record
 *   node tools/loop.mjs --no-build verify only
 *   node tools/loop.mjs --json     machine-readable summary on stdout
 *
 * Stages
 *   1. ASSEMBLE  concatenate the eight sections plus appendices and a generated
 *                table of figures into dist/PMS_Report.md
 *   2. VERIFY    run the gate in verify/verify.mjs as a child process
 *   3. RECORD    append a timestamped result to loop_log/build.log and refresh
 *                build/status.json
 *
 * The loop is idempotent: running it twice with no source change produces the
 * same report and the same verdict. It is the intended inner loop for the
 * project - edit a section, re-run, and the gate tells you what broke.
 */

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const SKIP_BUILD = argv.includes('--no-build');
const JSON_ONLY = argv.includes('--json');

const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'build/manifest.json'), 'utf8'));

const DIM = s => `\x1b[90m${s}\x1b[0m`;
const BOLD = s => `\x1b[1m${s}\x1b[0m`;
const GREEN = s => `\x1b[32m${s}\x1b[0m`;
const RED = s => `\x1b[31m${s}\x1b[0m`;

function log(...a) { if (!JSON_ONLY) console.log(...a); }

// ---------------------------------------------------------------------------
// Stage 1 — assemble
// ---------------------------------------------------------------------------
function assemble() {
  const parts = [];
  const warnings = [];

  const title = `# Patient Monitoring System — Design and Justification Record

**Biomedical Engineering assignment**

Five-bed centralised patient monitoring system: ward design, instrument
specification, system architecture, relational data model, digital health
integration, hospital management system linkage, and safety case.

*Generated by \`tools/loop.mjs\`. Do not edit this file directly — edit the
sections under \`report/\` and rebuild.*

---
`;

  parts.push(title);

  let n = 0;
  for (const fig of manifest.figures) {
    const abs = path.join(ROOT, fig.file);
    if (!fs.existsSync(abs)) { warnings.push('figure missing: ' + fig.file); continue; }
    n++;
    parts.push(`![${fig.caption}](${fig.file})\n\n*Figure ${n}. ${fig.caption}*\n`);
  }

  parts.push('---\n\n## Table of contents\n');
  for (const s of manifest.sections) parts.push(`${s.n}. ${s.title} — \`${s.file}\`\n`);
  for (const a of manifest.appendices) parts.push(`- Appendix ${a.id}: ${a.title} — \`${a.file}\`\n`);
  parts.push('\n---\n');

  for (const s of manifest.sections) {
    const abs = path.join(ROOT, s.file);
    if (!fs.existsSync(abs)) { warnings.push('section missing: ' + s.file); continue; }
    // The section files carry their own top-level heading; strip it to avoid
    // two H1s in the assembled document.
    let body = fs.readFileSync(abs, 'utf8').replace(/^# .*\r?\n\r?\n?/, '');
    parts.push(`\n<!-- source: ${s.file} -->\n\n` + body.trim() + '\n\n---\n');
  }

  for (const a of manifest.appendices) {
    const abs = path.join(ROOT, a.file);
    if (!fs.existsSync(abs)) { warnings.push('appendix missing: ' + a.file); continue; }
    let body = fs.readFileSync(abs, 'utf8').replace(/^# .*\r?\n\r?\n?/, '');
    parts.push(`\n<!-- source: ${a.file} -->\n\n` + body.trim() + '\n');
  }

  const outDir = path.join(ROOT, 'dist');
  fs.mkdirSync(outDir, { recursive: true });
  const outFile = path.join(outDir, 'PMS_Report.md');
  const doc = parts.join('\n');
  fs.writeFileSync(outFile, doc, 'utf8');

  return {
    file: path.relative(ROOT, outFile).replace(/\\/g, '/'),
    bytes: Buffer.byteLength(doc),
    words: doc.split(/\s+/).length,
    figures: n,
    sections: manifest.sections.filter(s => fs.existsSync(path.join(ROOT, s.file))).length,
    appendices: manifest.appendices.filter(a => fs.existsSync(path.join(ROOT, a.file))).length,
    warnings
  };
}

// ---------------------------------------------------------------------------
// Stage 2 — verify
// ---------------------------------------------------------------------------
function verify() {
  const res = spawnSync(process.execPath, [path.join(ROOT, 'verify/verify.mjs'), '--json'], {
    cwd: ROOT, encoding: 'utf8'
  });
  let status = {};
  try { status = JSON.parse(fs.readFileSync(path.join(ROOT, 'build/status.json'), 'utf8')); }
  catch { /* status file unwritten */ }
  return { code: res.status, status };
}

// ---------------------------------------------------------------------------
// Stage 3 — record
// ---------------------------------------------------------------------------
function record(build, v) {
  const logDir = path.join(ROOT, 'loop_log');
  fs.mkdirSync(logDir, { recursive: true });
  const stamp = new Date().toISOString();
  const verdict = v.code === 0 ? 'PASS' : 'FAIL';
  const line = [
    stamp,
    verdict.padEnd(4),
    `report=${build.bytes}B/${build.words}w`,
    `sections=${build.sections}/8`,
    `appendices=${build.appendices}/2`,
    `figures=${build.figures}/6`,
    `errors=${v.status.errors ?? '?'}`,
    `warnings=${v.status.warns ?? '?'}`
  ].join('  ') + '\n';
  fs.appendFileSync(path.join(logDir, 'build.log'), line, 'utf8');
  return line;
}

// ---------------------------------------------------------------------------
// run
// ---------------------------------------------------------------------------
let build = { bytes: 0, words: 0, figures: 0, sections: 0, appendices: 0, warnings: [], file: 'skipped' };
if (!SKIP_BUILD) build = assemble();
const v = verify();
const logLine = record(build, v);

if (JSON_ONLY) {
  console.log(JSON.stringify({ build, verify: v.status, exitCode: v.code }, null, 2));
} else {
  log('');
  log(BOLD('  PMS build loop'));
  log(DIM('  ' + '-'.repeat(64)));
  if (!SKIP_BUILD) {
    log(`  ${DIM('assembled')}  ${build.file}  ${build.bytes} B  ${build.words} words`);
    log(`  ${DIM('           ')}  ${build.sections}/8 sections  ${build.appendices}/2 appendices  ${build.figures}/6 figures`);
    for (const w of build.warnings) log(`  ${DIM('warn')}      ${w}`);
  }
  log(`  ${DIM('verdict  ')}  ${v.code === 0 ? GREEN('PASS') : RED('FAIL')}  ${v.status.errors ?? '?'} errors, ${v.status.warns ?? '?'} warnings`);
  log(DIM('  logged to loop_log/build.log'));
  log('');
}

process.exit(v.code);
